const dotenv =
   require("dotenv");

/* -------------------------------------------------------------------------- */
/*                            Load ENV                                        */
/* -------------------------------------------------------------------------- */

const envFile =
   `.env.${process.env.NODE_ENV || "development"}`;

dotenv.config({
   path: envFile
});

/* -------------------------------------------------------------------------- */
/*                          Initialize Listeners                              */
/* -------------------------------------------------------------------------- */

require(
   "./listeners"
);

/* -------------------------------------------------------------------------- */
/*                              App & DB                                      */
/* -------------------------------------------------------------------------- */

const app =
   require("./app");

const connectDB =
   require("./common/config/db");

const PORT =
   process.env.PORT || 5000;

connectDB().then(() => {
   /* -------------------------------------------------------------------------- */
   /*                              Start Server                                  */
   /* -------------------------------------------------------------------------- */
   app.listen(PORT, () => {
      console.log(
         `✅ Server running on port ${PORT}`
      );
   });
})
